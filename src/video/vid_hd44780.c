static inline int
hd44780_ddram_index(uint8_t addr)
{
    if (addr < HD44780_LINE_LEN)
        return addr;
    if ((addr >= 0x40) && (addr < (0x40 + HD44780_LINE_LEN)))
        return HD44780_LINE_LEN + (addr - 0x40);
    return -1;
}

static inline uint8_t
hd44780_ddram_next(uint8_t addr, int delta)
{
    if (delta > 0) {
        if (addr == (HD44780_LINE_LEN - 1))
            return 0x40;
        if (addr == (0x40 + HD44780_LINE_LEN - 1))
            return 0x00;
    } else {
        if (addr == 0x00)
            return 0x40 + HD44780_LINE_LEN - 1;
        if (addr == 0x40)
            return HD44780_LINE_LEN - 1;
    }
    return (addr + delta) & 0x7f;
}

static inline void
hd44780_advance(hd44780_lcd_t *lcd, int delta)
{
    if (lcd->addr & 0x80)
        lcd->addr = 0x80 | hd44780_ddram_next(lcd->addr & 0x7f, delta);
    else
        lcd->addr = 0x40 | ((lcd->addr + delta) & 0x3f);
}

static inline void
hd44780_shift(hd44780_lcd_t *lcd, int delta)
{
    lcd->shift = (lcd->shift + delta + HD44780_LINE_LEN) % HD44780_LINE_LEN;
}

static void
hd44780_render(hd44780_t *dev)
{
    for (int y = 0; y < dev->render_h; y++)
        memset(buffer32->line[y], 0x00, dev->render_w * sizeof(uint32_t));

    for (int y = 0; y < (dev->render_h - (2 * dev->y_offset)); y++) {
        uint32_t *line = &(buffer32->line[y + dev->y_offset][dev->x_offset]);
        for (int x = 0; x < (dev->render_w - (2 * dev->x_offset)); x++)
            line[x] = hd44780_palettes[dev->palette].panel;
    }

    for (int row = 0; row < dev->rows; row++) {
        hd44780_lcd_t *lcd = &dev->lcd[row >> 1];
        for (int col = 0; col < dev->cols; col++) {
            int            addr      = ((row & 1) ? HD44780_LINE_LEN : 0) + ((col + lcd->shift) % HD44780_LINE_LEN);
            int            is_cursor = (lcd->addr == (0x80 | addr)) && (lcd->config[1] & 0x02) && (lcd->frames < 30);
            uint8_t        ch        = lcd->ddram[addr];
            const uint8_t *glyph     = ((ch & 0xf8) == 0x00) ? &lcd->cgram[(ch & 0x07) << 3] : dev->font[ch];
            for (int dy = 0; dy < CHAR_H; dy++) {
                uint8_t bits = (lcd->config[1] & 0x04) ? (((dy == (CHAR_H - 1)) && is_cursor) ? 0xff : glyph[dy]) : 0x00; /* render blank if D cleared */
                for (int dx = 0; dx < CHAR_W; dx++) {
                    uint32_t color = (bits & (0x10 >> dx)) ? hd44780_palettes[dev->palette].on : hd44780_palettes[dev->palette].off;
                    int      px    = dev->x_offset + (MARGIN_DOTS * LCD_SCALE) + (((col * CELL_W) + dx) * LCD_SCALE);
                    int      py    = dev->y_offset + (MARGIN_DOTS * LCD_SCALE) + (((row * CELL_H) + dy) * LCD_SCALE);

                    for (int sy = 0; sy < dev->dot_size; sy++) {
                        uint32_t *line = &(buffer32->line[py + sy][px]);

                        for (int sx = 0; sx < dev->dot_size; sx++)
                            line[sx] = color;
                    }
                }
            }
        }
    }
}

static void
hd44780_poll(void *priv)
{
    hd44780_t *dev = (hd44780_t *) priv;

    timer_advance_u64(&dev->timer, (uint64_t) ((TIMER_USEC * 1000000.0) / 60.0));

    dev->prev_monitor_index = monitor_index_global;
    monitor_index_global    = dev->monitor_index;

    if (video_force_resize_get()) {
        set_screen_size(dev->render_w, dev->render_h);
        video_force_resize_set(0);
    }

    for (int i = 0; i < (sizeof(dev->lcd) / sizeof(dev->lcd[0])); i++) {
        if (dev->lcd[i].config[1] & 0x01) {
            int frames = ++dev->lcd[i].frames;
            if (frames == 30) {
                dev->redraw = 1;
            } else if (frames >= 60) {
                dev->redraw        = 1;
                dev->lcd[i].frames = 0;
            }
        }
    }

    video_wait_for_buffer();
    if (dev->redraw) {
        hd44780_render(dev);
        dev->redraw = 0;
    }
    video_blit_memtoscreen(0, 0, dev->render_w, dev->render_h);

    video_res_x = dev->cols;
    video_res_y = dev->rows;
    video_bpp   = 0;

    frames++;

    monitor_index_global = dev->prev_monitor_index;
}

static void
hd44780_clock(hd44780_t *dev, hd44780_lcd_t *lcd, uint8_t rs, uint8_t rw, uint8_t val)
{
    hd44780_log(dev->log, "clock(%X, %X, %08X)\n", rs, rw, val);

    if (!(lcd->config[3] & 0x10)) { /* 4-bit mode */
        if (!lcd->nibble) {
            lcd->latch  = val;
            lcd->nibble = 1;
            return;
        }
        val = (lcd->latch & 0xf0) | (val >> 4);
    }
    lcd->nibble = 0;

    if (rs) { /* CGRAM/DDRAM access */
        int is_ddram = !!(lcd->addr & 0x80);
        int idx      = is_ddram ? hd44780_ddram_index(lcd->addr & 0x7f) : (lcd->addr & 0x3f);

        if (rw) { /* read */
            lpt_write_to_dat(dev->lpt, (idx < 0) ? ' ' : (is_ddram ? lcd->ddram[idx] : lcd->cgram[idx]));
        } else if (idx >= 0) { /* write */
            if (is_ddram)
                lcd->ddram[idx] = val;
            else
                lcd->cgram[idx] = val;
            dev->redraw = 1;
        }

        hd44780_advance(lcd, (lcd->config[0] & 0x02) ? 1 : -1);
        if (is_ddram && (lcd->config[0] & 0x01)) { /* apply shift */
            hd44780_shift(lcd, (lcd->config[0] & 0x02) ? 1 : -1);
            dev->redraw = 1;
        }
    } else {      /* command */
        if (rw) { /* read address */
            lpt_write_to_dat(dev->lpt, lcd->addr & ((lcd->addr & 0x80) ? 0x7f : 0x3f));
        } else if (val & 0xc0) { /* set address */
            lcd->addr = val;
        } else if (val & 0x20) { /* function set */
            lcd->config[3] = val;
        } else if (val & 0x10) { /* cursor/display shift */
            lcd->config[2] = val;
            if (val & 0x08)
                hd44780_shift(lcd, (val & 0x04) ? -1 : 1);
            else
                hd44780_advance(lcd, (val & 0x04) ? 1 : -1);
            dev->redraw = 1;
        } else if (val & 0x08) { /* display control */
            if ((val ^ lcd->config[1]) & 0x01)
                lcd->frames = 0;
            lcd->config[1] = val;
            dev->redraw    = 1;
        } else if (val & 0x04) {  /* entry mode set */
            lcd->config[0] = val; /* entry mode set */
        } else if (val & 0x02) {  /* cursor home */
            lcd->addr   = 0x80;
            lcd->shift  = 0;
            dev->redraw = 1;
        } else if (val & 0x01) { /* clear display */
            memset(lcd->ddram, ' ', sizeof(lcd->ddram));
            lcd->addr  = 0x80;
            lcd->shift = 0;
            lcd->config[0] |= 0x02; /* set increment mode as well */
            dev->redraw = 1;
        }
    }
}

static void
hd44780_write_data(uint8_t val, void *priv)
{
    hd44780_t *dev = (hd44780_t *) priv;

    if (dev->wiring == HD44780_WIRING_4BIT) {                                            /* control on D[7:4] in 4-bit mode */
        if ((dev->data & 0x40) && !(val & 0x40))                                         /* primary E on D6 */
            hd44780_clock(dev, &dev->lcd[0], val & 0x10, val & 0x20, (val << 4) | 0x0f); /* RS on D4, R/W on D5, 4-bit data on D[3:0] */
        if ((dev->controllers > 1) && (dev->data & 0x80) && !(val & 0x80))               /* secondary E on D7 */
            hd44780_clock(dev, &dev->lcd[1], val & 0x10, val & 0x20, (val << 4) | 0x0f); /* same as above */
    }

    dev->data = val;
}

static void
hd44780_write_ctrl(uint8_t val, void *priv)
{
    hd44780_t *dev = (hd44780_t *) priv;

    if (dev->wiring == HD44780_WIRING_8BIT) {               /* control on control port in 8-bit mode */
        if ((dev->type == HD44780_QUBE3) && (val & 0x08)) { /* Cobalt Qube 3 buttons on SelectIn */
            lpt_write_to_dat(dev->lpt, dev->buttons ? dev->buttons : 0xfe);
            return;
        }

        if ((dev->ctrl & 0x01) && !(val & 0x01))                                    /* primary E on nStrobe */
            hd44780_clock(dev, &dev->lcd[0], val & 0x04, !(val & 0x02), dev->data); /* RS on nInit, R/W on autofd, 8-bit data on D[7:0] */
        if ((dev->controllers > 1) && (dev->ctrl & 0x08) && !(val & 0x08))          /* secondary E on SelectIn */
            hd44780_clock(dev, &dev->lcd[1], val & 0x04, !(val & 0x02), dev->data); /* same as above */
    }

    dev->ctrl = val;
}

static void
hd44780_qube3_keyboard_send(uint16_t val)
{
    hd44780_t *dev = (hd44780_t *) device_get_priv(&hd44780_qube3_device);
    if (!dev)
        return;

    hd44780_log(dev->log, "keyboard_send(%04X)\n", val);
}

static void
hd44780_recalc_size(hd44780_t *dev)
{
    int panel_w = ((dev->cols * CELL_W) - CELL_GAP + (2 * MARGIN_DOTS)) * LCD_SCALE;
    int panel_h = ((dev->rows * CELL_H) - CELL_GAP + (2 * MARGIN_DOTS)) * LCD_SCALE;
    if (dev->monitor_index == 0) {
        dev->render_w = MAX(panel_w, CANVAS_W);
        dev->render_h = MAX(panel_h, CANVAS_H);
    } else {
        dev->render_w = panel_w;
        dev->render_h = panel_h;
    }

    dev->x_offset = (dev->render_w - panel_w) / 2;
    dev->y_offset = (dev->render_h - panel_h) / 2;
}

