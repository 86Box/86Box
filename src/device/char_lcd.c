static void
lcd_lock(void)
{
    if (lcd_mutex != NULL)
        thread_wait_mutex(lcd_mutex);
}

static void
lcd_unlock(void)
{
    if (lcd_mutex != NULL)
        thread_release_mutex(lcd_mutex);
}

static void
lcd_busy_done(UNUSED(void *priv))
{
    lcd.busy = 0;
}

static void
lcd_set_busy(double us)
{
    lcd.busy = 1;
    timer_on_auto(&lcd.busy_timer, us);
}

/* Where a DDRAM address is kept. */
static int
lcd_ddram_index(uint8_t addr)
{
    if (lcd.n)
        return ((addr & 0x40) ? LCD_LINE_LEN : 0) + ((addr & 0x3f) % LCD_LINE_LEN);

    return (addr & 0x7f) % LCD_DDRAM_SIZE;
}

/* Moves the address counter by one, wrapping as the controller does. */
static void
lcd_ac_step(int up)
{
    if (lcd.ac_cg) {
        lcd.ac = (lcd.ac + (up ? 1 : -1)) & (LCD_CGRAM_SIZE - 1);
        return;
    }

    if (lcd.n) {
        /* 2-line: 0x27 goes on to 0x40, 0x67 back to 0x00, and the other way. */
        uint8_t line = lcd.ac & 0x40;
        int     pos  = lcd.ac & 0x3f;

        if (pos >= LCD_LINE_LEN)
            pos = LCD_LINE_LEN - 1;

        pos += up ? 1 : -1;
        if (pos >= LCD_LINE_LEN) {
            pos = 0;
            line ^= 0x40;
        } else if (pos < 0) {
            pos = LCD_LINE_LEN - 1;
            line ^= 0x40;
        }
        lcd.ac = line | pos;
    } else {
        int pos = (lcd.ac & 0x7f) % LCD_DDRAM_SIZE;

        pos += up ? 1 : -1;
        if (pos >= LCD_DDRAM_SIZE)
            pos = 0;
        else if (pos < 0)
            pos = LCD_DDRAM_SIZE - 1;
        lcd.ac = pos;
    }
}

/* Shifts the display one character, left if asked. */
static void
lcd_display_shift(int left)
{
    int len = lcd.n ? LCD_LINE_LEN : LCD_DDRAM_SIZE;

    lcd.shift = (lcd.shift + (left ? 1 : (len - 1))) % len;
}

static uint8_t
lcd_ram_read(void)
{
    if (lcd.ac_cg)
        return lcd.cgram[lcd.ac & (LCD_CGRAM_SIZE - 1)];

    return lcd.ddram[lcd_ddram_index(lcd.ac)];
}

static void
lcd_clear(void)
{
    memset(lcd.ddram, 0x20, sizeof(lcd.ddram));
    lcd.ac    = 0x00;
    lcd.ac_cg = 0;
    lcd.id    = 1;
    lcd.shift = 0;
}

static void
lcd_instruction(uint8_t val)
{
    double t = LCD_T_INST;

    if (val & 0x80) {
        /* Set DDRAM address. */
        lcd.ac    = val & 0x7f;
        lcd.ac_cg = 0;
        lcd.dr    = lcd_ram_read();
    } else if (val & 0x40) {
        /* Set CGRAM address. */
        lcd.ac    = val & 0x3f;
        lcd.ac_cg = 1;
        lcd.dr    = lcd_ram_read();
    } else if (val & 0x20) {
        /* Function set. */
        lcd.dl = !!(val & 0x10);
        lcd.n  = !!(val & 0x08);
        lcd.f  = !!(val & 0x04);
        if (lcd.dl)
            lcd.nibble = 0;
        lcd.shift %= lcd.n ? LCD_LINE_LEN : LCD_DDRAM_SIZE;
    } else if (val & 0x10) {
        /* Cursor or display shift. */
        if (val & 0x08)
            lcd_display_shift(!(val & 0x04));
        else {
            lcd_ac_step(!!(val & 0x04));
            lcd.dr = lcd_ram_read();
        }
    } else if (val & 0x08) {
        /* Display on/off control. */
        lcd.d = !!(val & 0x04);
        lcd.c = !!(val & 0x02);
        lcd.b = !!(val & 0x01);
    } else if (val & 0x04) {
        /* Entry mode set. */
        lcd.id = !!(val & 0x02);
        lcd.s  = !!(val & 0x01);
    } else if (val & 0x02) {
        /* Return home. */
        lcd.ac    = 0x00;
        lcd.ac_cg = 0;
        lcd.shift = 0;
        t         = LCD_T_CLEAR;
    } else if (val & 0x01) {
        lcd_clear();
        t = LCD_T_CLEAR;
    }

    lcd_set_busy(t);
}

static void
lcd_data_write(uint8_t val)
{
    if (lcd.ac_cg)
        lcd.cgram[lcd.ac & (LCD_CGRAM_SIZE - 1)] = val;
    else {
        lcd.ddram[lcd_ddram_index(lcd.ac)] = val;
        if (lcd.s)
            lcd_display_shift(lcd.id);
    }

    lcd.dr = val;
    lcd_ac_step(lcd.id);
    lcd_set_busy(LCD_T_DATA);
}

static uint8_t
lcd_data_read(void)
{
    uint8_t ret = lcd.dr;

    lcd_ac_step(lcd.id);
    lcd.dr = lcd_ram_read();
    lcd_set_busy(LCD_T_DATA);

    return ret;
}

/* A whole 8-bit transfer. */
static void
lcd_write(int rs, uint8_t val)
{
    char_lcd_log("CharLCD: %s %02X\n", rs ? "data" : "instruction", val);

    /* Real controllers drop what arrives while they are busy, but software
       that relies on bus timing to wait may run faster here, so it is
       always taken. The busy flag still reads as the real thing's would. */
    if (rs)
        lcd_data_write(val);
    else
        lcd_instruction(val);

    lcd.written = 1;
}

static uint8_t
lcd_read(int rs)
{
    if (rs)
        return lcd_data_read();

    return (lcd.busy ? 0x80 : 0x00) | (lcd.ac & 0x7f);
}

static uint8_t
lcd_bus_read_locked(int rs)
{
    uint8_t ret;

    if (lcd.dl)
        return lcd_read(rs);

    /* 4-bit: the high nibble, then the low, on D7-D4; D3-D0 float high. */
    if (!lcd.nibble) {
        lcd.rd_hold = lcd_read(rs);
        ret         = lcd.rd_hold | 0x0f;
    } else
        ret = (lcd.rd_hold << 4) | 0x0f;
    lcd.nibble ^= 1;

    return ret;
}

static void
lcd_bus_write_locked(int rs, uint8_t val)
{
    if (lcd.dl) {
        lcd_write(rs, val);
        return;
    }

    if (!lcd.nibble) {
        lcd.wr_hold = val & 0xf0;
        lcd.nibble  = 1;
    } else {
        lcd.nibble = 0;
        lcd_write(rs, lcd.wr_hold | (val >> 4));
    }
}

uint8_t
char_lcd_bus_read(int rs)
{
    uint8_t ret = 0xff;

    if (lcd.present) {
        lcd_lock();
        ret = lcd_bus_read_locked(rs);
        lcd_unlock();
    }

    return ret;
}

void
char_lcd_bus_write(int rs, uint8_t val)
{
    if (lcd.present) {
        lcd_lock();
        lcd_bus_write_locked(rs, val);
        lcd_unlock();
    }
}

/*
   EN's rising edge starts a read, whose data the module then drives until
   EN falls; its falling edge latches a write.
 */
int
char_lcd_pins(int rs, int rw, int en, uint8_t data)
{
    int ret = -1;

    if (!lcd.present)
        return ret;

    lcd_lock();

    en = !!en;
    if (en && !lcd.pin_en && rw)
        lcd.pin_out = lcd_bus_read_locked(rs);
    else if (!en && lcd.pin_en && !rw)
        lcd_bus_write_locked(rs, data);
    lcd.pin_en = en;

    if (en && rw)
        ret = lcd.pin_out;

    lcd_unlock();

    return ret;
}

