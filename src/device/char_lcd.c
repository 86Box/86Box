typedef struct char_lcd_t {
    int present;
    int cols;
    int rows;
    int panel;

    uint32_t generation;
    int      written; /* Something has written to it since power-up. */

    uint8_t ddram[LCD_DDRAM_SIZE];
    uint8_t cgram[LCD_CGRAM_SIZE];

    uint8_t ac;       /* Address counter. */
    uint8_t ac_cg;    /* The last address set was a CGRAM one. */
    uint8_t dr;       /* Data register, which reads come from. */
    uint8_t shift;    /* Display shift, in characters to the left. */

    uint8_t id;       /* Entry mode: increment. */
    uint8_t s;        /* Entry mode: shift the display with writes. */
    uint8_t d;        /* Display on. */
    uint8_t c;        /* Cursor on. */
    uint8_t b;        /* Blink on. */
    uint8_t dl;       /* 8-bit interface. */
    uint8_t n;        /* 2-line mode. */
    uint8_t f;        /* 5x10 font. */

    uint8_t nibble;   /* In 4-bit mode, the second nibble is next. */
    uint8_t wr_hold;  /* The first nibble of a write. */
    uint8_t rd_hold;  /* What a read's second nibble returns. */

    volatile uint8_t busy;

    /* The pins, for the pin interface. */
    uint8_t pin_en;
    uint8_t pin_out;

    uint16_t base; /* ISA I/O base, 0 if none. */

    pc_timer_t busy_timer; /* Last: a power-up clears everything before it. */
} char_lcd_t;

