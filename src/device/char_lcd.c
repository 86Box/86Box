/*
 * 86Box    A hypervisor and IBM PC system emulator that specializes in
 *          running old operating systems and software designed for IBM
 *          PC systems and compatibles from 1981 through fairly recent
 *          system designs based on the PCI bus.
 *
 *          This file is part of the 86Box distribution.
 *
 *          HD44780 character LCD module.
 *
 *          A Hitachi HD44780 (or one of its many clones) with the A00
 *          (Japanese) character ROM, on 16x2, 20x4 or 40x2 glass. All of the
 *          controller is emulated: the 8- and 4-bit interfaces, DDRAM and
 *          CGRAM with their address counter wrapping, the entry modes,
 *          cursor and display shifts, the underline and blinking cursors,
 *          1- and 2-line modes, 5x8 and 5x10 fonts, reads of RAM and of the
 *          busy flag and address counter, and the time each instruction
 *          keeps it busy for.
 *
 *          A board with an LCD bus or header drives it through the bus
 *          cycle or pin functions; on others, it can sit at two ISA I/O
 *          ports (instruction register first), or on a parallel port wired
 *          the usual "Winamp" way: D0-D7 to the data pins, nSTROBE to EN,
 *          nAUTOFD to R/W and nINIT to RS.
 *
 *          The module is a single instance with its state kept statically,
 *          so that the user interface, which polls it from its own thread,
 *          never sees it freed.
 *
 * Authors: Nathan Lewis, <git@nrlewis.dev>
 *
 *          Copyright 2026 Nathan Lewis.
 */
