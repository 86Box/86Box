static void *
char_lcd_init(UNUSED(const device_t *info))
{
    uint32_t generation;
    int      size;

    if (lcd_mutex == NULL)
        lcd_mutex = thread_create_mutex();

    lcd_lock();

    generation = lcd.generation;
    memset(&lcd, 0x00, offsetof(char_lcd_t, busy_timer));
    lcd.generation = generation + 1;

    size = device_get_config_int("size");
    switch (size) {
        case 2004:
            lcd.cols = 20;
            lcd.rows = 4;
            break;
        case 4002:
            lcd.cols = 40;
            lcd.rows = 2;
            break;
        default:
            lcd.cols = 16;
            lcd.rows = 2;
            break;
    }
    lcd.panel = device_get_config_int("panel");
    lcd.base  = device_get_config_hex16("base");

    /* The internal reset: cleared, 8-bit, 1-line, 5x8, display off,
       incrementing without shifting. CGRAM comes up as whatever it holds. */
    for (int i = 0; i < LCD_CGRAM_SIZE; i++)
        lcd.cgram[i] = (uint8_t) (rand() & 0xff);
    lcd_clear();
    lcd.dl = 1;

    lcd.present = 1;

    lcd_unlock();

    timer_add(&lcd.busy_timer, lcd_busy_done, NULL, 0);
    lcd_set_busy(LCD_T_POWER_ON);

    if (lcd.base)
        io_sethandler(lcd.base, 2, lcd_io_read, NULL, NULL, lcd_io_write, NULL, NULL, NULL);

    return &lcd;
}

static void
char_lcd_close(UNUSED(void *priv))
{
    if (lcd.base)
        io_removehandler(lcd.base, 2, lcd_io_read, NULL, NULL, lcd_io_write, NULL, NULL, NULL);

    lcd_lock();
    lcd.present = 0;
    lcd.written = 0;
    lcd_unlock();

    timer_disable(&lcd.busy_timer);
}

