#!/bin/sh
# Regenerate the embedded SPIR-V of the RIVA TNT GPU lane
# (src/video/nv/nv4/subsystems/nv4_pgraph_3d_gpu.comp) into
# src/include/86box/nv/nv4_3d_gpu_spv.h. The header is committed, so
# glslc (shaderc) is only needed when the kernel changes.
set -e
cd "$(dirname "$0")/.."

GLSLC=${GLSLC:-glslc}
SRC=src/video/nv/nv4/subsystems/nv4_pgraph_3d_gpu.comp
OUT=src/include/86box/nv/nv4_3d_gpu_spv.h
TMP=$(mktemp)

$GLSLC --target-env=vulkan1.1 -O -o "$TMP" "$SRC"
{
    echo "/* Generated by scripts/regen-nv4-gpu-spv.sh from"
    echo "   nv4_pgraph_3d_gpu.comp -- do not edit. Tool:"
    echo "   $($GLSLC --version | head -n 1)"
    echo "*/"
    echo "static const unsigned char nv4_gpu_spv[] = {"
    od -An -v -tx1 "$TMP" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/  /; s/, *$/,/'
    echo "};"
} > "$OUT"
rm -f "$TMP"
echo "wrote $OUT"
